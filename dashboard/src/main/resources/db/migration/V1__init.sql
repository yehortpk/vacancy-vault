-- The dashboard's read model: every vacancy the crawler has published and not yet removed.
--
-- The company is plain columns rather than a table of its own: each new vacancy carries its
-- company's id, title and URL, so the dashboard never needs a company row, and nothing here
-- references another service's schema.
--
-- A salary bound the source did not publish is NULL, and the amounts are kept in the currency
-- and period they were published in rather than converted.

CREATE TABLE vacancy (
    vacancy_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    link            VARCHAR(255) NOT NULL,
    title           VARCHAR(255),
    description     TEXT,
    min_salary      INTEGER,
    max_salary      INTEGER,
    salary_currency VARCHAR(16),
    salary_period   VARCHAR(16),
    is_remote       BOOLEAN      NOT NULL,
    crawled_at      TIMESTAMP(6),
    company_id      INTEGER      NOT NULL,
    company_title   VARCHAR(255),
    company_url     VARCHAR(255),
    PRIMARY KEY (vacancy_id),
    CONSTRAINT uk_vacancy_link UNIQUE (link)
);
