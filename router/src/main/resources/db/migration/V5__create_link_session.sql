-- One attempt to link a destination, identified by a token valid for 15 minutes and usable
-- once.
--
-- The user gets the token together with the provider's link instructions, follows them in
-- the messenger, and the provider's service reports the token back with the destination.
-- Whoever presents the token links a destination to its owner, so only a SHA-256 of it is
-- stored: the token is 256 random bits, which a fast hash protects as well as BCrypt would,
-- and the hash stays an indexed exact-match lookup.
--
-- connection_id records what the session produced; it becomes NULL when that connection is
-- later unlinked.

CREATE TABLE link_session (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    provider_id   BIGINT       NOT NULL REFERENCES provider (id),
    token_hash    VARCHAR(64)  NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    expires_at    TIMESTAMP(6) NOT NULL,
    consumed_at   TIMESTAMP(6),
    connection_id BIGINT       REFERENCES connection (id) ON DELETE SET NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_link_session_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_link_session_user_id ON link_session (user_id);
