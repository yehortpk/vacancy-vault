-- Baseline of the schema as it existed under MySQL, translated to PostgreSQL.
--
-- Flyway now owns the schema outright: the notifier-dump.sql init mount is gone and the
-- data it used to seed arrives through the repeatable R__seed_* migrations instead.
-- The MySQL dump's AUTO_INCREMENT counters are dropped here; the seed migrations advance
-- the identity sequences past the rows they insert.

CREATE TABLE company (
    company_id        INTEGER      NOT NULL,
    bean_class        VARCHAR(255),
    title             VARCHAR(255),
    parsing_enabled   BOOLEAN      NOT NULL,
    main_page_url     VARCHAR(255),
    vacancies_url     VARCHAR(255),
    api_vacancies_url VARCHAR(255),
    PRIMARY KEY (company_id)
);

CREATE TABLE company_data (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    data_key   VARCHAR(255),
    data_value VARCHAR(255),
    company_id INTEGER REFERENCES company (company_id),
    PRIMARY KEY (id)
);

CREATE INDEX idx_company_data_company_id ON company_data (company_id);

CREATE TABLE company_headers (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    header_key   VARCHAR(255),
    header_value TEXT,
    company_id   INTEGER REFERENCES company (company_id),
    PRIMARY KEY (id)
);

CREATE INDEX idx_company_headers_company_id ON company_headers (company_id);

CREATE TABLE company_cookies (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cookie_key   VARCHAR(255),
    cookie_value TEXT,
    company_id   INTEGER REFERENCES company (company_id),
    PRIMARY KEY (id)
);

CREATE INDEX idx_company_cookies_company_id ON company_cookies (company_id);

CREATE TABLE vacancy (
    vacancy_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    delete_at  TIMESTAMP(6),
    is_remote  BOOLEAN      NOT NULL,
    link       VARCHAR(255) NOT NULL,
    max_salary INTEGER      NOT NULL,
    min_salary INTEGER      NOT NULL,
    parsed_at  TIMESTAMP(6),
    title      VARCHAR(255),
    company_id INTEGER REFERENCES company (company_id),
    PRIMARY KEY (vacancy_id),
    CONSTRAINT uk_vacancy_link UNIQUE (link)
);

CREATE INDEX idx_vacancy_company_id ON vacancy (company_id);

CREATE TABLE client (
    chat_id BIGINT NOT NULL,
    PRIMARY KEY (chat_id)
);

CREATE TABLE filter (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    filter    TEXT,
    client_id BIGINT NOT NULL REFERENCES client (chat_id),
    PRIMARY KEY (id)
);

CREATE INDEX idx_filter_client_id ON filter (client_id);
