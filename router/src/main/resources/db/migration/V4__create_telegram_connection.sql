-- One user's linked Telegram destination.
--
-- Each messenger gets its own connection table with its own real field names and types, so
-- chat_id is a typed BIGINT with its own UNIQUE constraint rather than a stringified id
-- sharing a column with other platforms. A future messenger adds its own table in its own
-- migration; this file is never edited to accommodate one.
--
-- The UNIQUE on chat_id is what makes one chat belong to at most one account, so the bot
-- cannot be made to deliver one chat's notifications to two users.

CREATE TABLE telegram_connection (
    id        BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id   BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    chat_id   BIGINT       NOT NULL,
    title     VARCHAR(255),
    linked_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_telegram_connection_chat_id UNIQUE (chat_id)
);

CREATE INDEX idx_telegram_connection_user_id ON telegram_connection (user_id);
