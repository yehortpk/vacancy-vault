-- Catalog of messenger platforms a user can be notified through.
--
-- This table deliberately holds no address: `code` identifies a platform, and a platform is
-- not a destination. The per-user address lives on the user-to-provider link row, in that
-- provider's own *_connection table.

CREATE TABLE provider (
    id      BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    code    VARCHAR(32)  NOT NULL,
    title   VARCHAR(255) NOT NULL,
    enabled BOOLEAN      NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_provider_code UNIQUE (code)
);

