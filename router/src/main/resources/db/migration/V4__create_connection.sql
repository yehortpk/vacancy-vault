-- One linked destination of one account, whatever the messenger.
--
-- This is the only connection table the core reads: listing, renaming, unlinking, ownership
-- checks and filter bindings all work on it. What a destination actually is (a chat id, a
-- webhook URL) lives in that provider's own *_connection table, which references this one.
--
-- UNIQUE (id, provider_id) is the target of the details tables' composite foreign key, which
-- stops one provider's details row from hanging off another provider's connection.

CREATE TABLE connection (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    provider_id BIGINT       NOT NULL REFERENCES provider (id),
    title       VARCHAR(255),
    linked_at   TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_connection_id_provider_id UNIQUE (id, provider_id)
);

CREATE INDEX idx_connection_user_id ON connection (user_id);
