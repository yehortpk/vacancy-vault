-- Native accounts: the platform becomes its own identity provider.
--
-- Named app_user rather than user: "user" needs quoting in PostgreSQL, where CURRENT_USER
-- makes the bare word ambiguous.
--
-- Roles: every account is a USER; an ADMIN may additionally start the parser and watch its
-- progress. There is no endpoint that grants ADMIN - it is assigned directly in the
-- database, so registering can never escalate an account.
--
-- The role is stored as the enum name rather than a lookup table: there are two fixed values
-- and the application maps them with @Enumerated(STRING). The CHECK keeps a typo out of the
-- column.

CREATE TABLE app_user (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    role          VARCHAR(16)  NOT NULL DEFAULT 'USER',
    PRIMARY KEY (id),
    CONSTRAINT uk_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_role CHECK (role IN ('USER', 'ADMIN'))
);

-- Email is the login identifier, so every authentication attempt looks a row up by it.
