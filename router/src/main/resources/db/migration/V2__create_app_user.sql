-- Native accounts: the platform becomes its own identity provider.
--
-- Named app_user rather than user: "user" needs quoting in both PostgreSQL (where
-- CURRENT_USER makes the bare word ambiguous) and MySQL (where it is reserved).
--
-- api_key_prefix is stored in the clear on purpose: it turns resolving a pasted key into
-- an indexed single-row lookup, instead of a BCrypt comparison against every account.
-- Only the secret half is hashed.

CREATE TABLE app_user (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    email          VARCHAR(255) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    api_key_hash   VARCHAR(100),
    api_key_prefix VARCHAR(16),
    created_at     TIMESTAMP(6) NOT NULL,
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_app_user_email UNIQUE (email)
);

-- Email is the login identifier, so every authentication attempt looks a row up by it.
-- The UNIQUE constraint above already provides the index.

CREATE UNIQUE INDEX uk_app_user_api_key_prefix ON app_user (api_key_prefix);
