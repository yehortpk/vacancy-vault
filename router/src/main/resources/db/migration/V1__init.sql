-- The router's schema: accounts, the destinations they linked, their filters, and the links
-- already notified about. Vacancies and companies are not here: they belong to the dashboard
-- and the parser.

-- Native accounts: the router is the identity provider of the platform's users.
--
-- Named app_user rather than user: "user" needs quoting in PostgreSQL, where CURRENT_USER
-- makes the bare word ambiguous.
--
-- There are no roles: an account reaches its own data under /me and nothing else. The
-- parser's operators are a separate table in the parser's own schema.
--
-- Email is the login identifier, so every authentication attempt looks a row up by it; the
-- UNIQUE constraint provides the index.
CREATE TABLE app_user (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_app_user_email UNIQUE (email)
);

-- Catalog of messenger platforms a user can be notified through.
--
-- Each provider's row has a fixed id, which its ConnectionProvider declares, so the id is not
-- an identity column.
--
-- This table deliberately holds no destination: a platform is not somewhere to send a
-- message. A user's destination is a connection row plus that provider's own *_connection
-- details row.
--
-- link_instructions is what the user is told to do after starting a link. The core replaces
-- {token} with the session's one-time token, and the CHECK keeps the placeholder from being
-- forgotten.
CREATE TABLE provider (
    id                BIGINT       NOT NULL,
    title             VARCHAR(255) NOT NULL,
    link_instructions TEXT         NOT NULL,
    enabled           BOOLEAN      NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT ck_provider_link_instructions_token CHECK (link_instructions LIKE '%{token}%')
);

-- One linked destination of one account, whatever the messenger.
--
-- This is the only connection table the core reads: listing, renaming, unlinking, ownership
-- checks and filter bindings all work on it. What a destination actually is (a chat id, a
-- webhook URL) lives in that provider's own *_connection table, which references this one.
--
-- UNIQUE (id, provider_id) is the target of the details tables' composite foreign key, which
-- stops one provider's details row from hanging off another provider's connection.
CREATE TABLE connection (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    provider_id BIGINT       NOT NULL REFERENCES provider (id),
    title       VARCHAR(255),
    linked_at   TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_connection_id_provider_id UNIQUE (id, provider_id)
);

CREATE INDEX idx_connection_user_id ON connection (user_id);

-- One attempt to link a destination, identified by a token valid for 15 minutes and usable
-- once.
--
-- The user gets the token together with the provider's link instructions, follows them in
-- the messenger, and the provider's service reports the token back with the destination.
-- Whoever presents the token links a destination to its owner, so only a SHA-256 of it is
-- stored: the token is 256 random bits, which a fast hash protects as well as BCrypt would,
-- and the hash stays an indexed exact-match lookup.
--
-- connection_id records what the session produced; it becomes NULL when that connection is
-- later unlinked.
CREATE TABLE link_session (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    provider_id   BIGINT       NOT NULL REFERENCES provider (id),
    token_hash    VARCHAR(64)  NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    expires_at    TIMESTAMP(6) NOT NULL,
    consumed_at   TIMESTAMP(6),
    connection_id BIGINT       REFERENCES connection (id) ON DELETE SET NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_link_session_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_link_session_user_id ON link_session (user_id);

-- The Telegram provider: its catalog row and its details table. provider_id is fixed to 1 and
-- part of the foreign key, so a row here can only belong to a Telegram connection. The UNIQUE
-- on chat_id makes one chat belong to at most one account.
INSERT INTO provider (id, title, link_instructions) VALUES (
    1,
    'Telegram',
    'Send /link {token} to the Telegram bot from the chat that should receive notifications.'
);

CREATE TABLE telegram_connection (
    connection_id BIGINT NOT NULL,
    provider_id   BIGINT NOT NULL DEFAULT 1,
    chat_id       BIGINT NOT NULL,
    PRIMARY KEY (connection_id),
    CONSTRAINT fk_telegram_connection_connection FOREIGN KEY (connection_id, provider_id)
        REFERENCES connection (id, provider_id) ON DELETE CASCADE,
    CONSTRAINT ck_telegram_connection_provider_id CHECK (provider_id = 1),
    CONSTRAINT uk_telegram_connection_chat_id UNIQUE (chat_id)
);

-- A vacancy filter an account authors in the web app: a name to be listed by, and the
-- expression new vacancies are matched against.
CREATE TABLE filter (
    id      BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    filter  TEXT         NOT NULL,
    user_id BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    title   VARCHAR(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE INDEX idx_filter_user_id ON filter (user_id);

-- Binds a filter to the connections it notifies. A filter with no row here is a draft. Both
-- foreign keys cascade, so unlinking a connection or deleting a filter cleans up on its own.
CREATE TABLE filter_connection (
    filter_id     BIGINT NOT NULL REFERENCES filter (id) ON DELETE CASCADE,
    connection_id BIGINT NOT NULL REFERENCES connection (id) ON DELETE CASCADE,
    PRIMARY KEY (filter_id, connection_id)
);

CREATE INDEX idx_filter_connection_connection_id ON filter_connection (connection_id);

-- The links of the vacancies already matched against the filters. A new_vacancies message
-- whose link is here is a redelivery or a replay and notifies nobody. Rows older than the
-- topic's retention are swept away, since the topic can no longer replay them.
CREATE TABLE notified_vacancy (
    link        VARCHAR(255) NOT NULL,
    notified_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (link)
);

-- The sweeper deletes by age
CREATE INDEX idx_notified_vacancy_notified_at ON notified_vacancy (notified_at);
