-- Everything the parser needs to work on its own: the companies it crawls, its memory of the
-- vacancies it has already published, and the operators of its admin panel.

-- Companies are added by hand. bean_class names the crawler bean that parses the company.
CREATE TABLE company (
    company_id        INTEGER      NOT NULL,
    bean_class        VARCHAR(255),
    title             VARCHAR(255),
    parsing_enabled   BOOLEAN      NOT NULL,
    main_page_url     VARCHAR(255),
    vacancies_url     VARCHAR(255),
    api_vacancies_url VARCHAR(255),
    PRIMARY KEY (company_id)
);

CREATE TABLE company_data (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    data_key   VARCHAR(255),
    data_value VARCHAR(255),
    company_id INTEGER REFERENCES company (company_id),
    PRIMARY KEY (id)
);

CREATE INDEX idx_company_data_company_id ON company_data (company_id);

CREATE TABLE company_headers (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    header_key   VARCHAR(255),
    header_value TEXT,
    company_id   INTEGER REFERENCES company (company_id),
    PRIMARY KEY (id)
);

CREATE INDEX idx_company_headers_company_id ON company_headers (company_id);

CREATE TABLE company_cookies (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cookie_key   VARCHAR(255),
    cookie_value TEXT,
    company_id   INTEGER REFERENCES company (company_id),
    PRIMARY KEY (id)
);

CREATE INDEX idx_company_cookies_company_id ON company_cookies (company_id);

-- One row per vacancy already published to new_vacancies, written after the broker's ack. A run
-- publishes only the links missing here.
--
-- delete_at is the grace period of a vacancy that disappeared from its site: set to a week
-- ahead when it is first missed, cleared if it shows up again, and once it has passed the row
-- is dropped and the link goes to removed_vacancies.
CREATE TABLE parsed_vacancy (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    link       VARCHAR(255) NOT NULL,
    company_id INTEGER      NOT NULL REFERENCES company (company_id),
    parsed_at  TIMESTAMP(6) NOT NULL,
    delete_at  TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uk_parsed_vacancy_link UNIQUE (link)
);

CREATE INDEX idx_parsed_vacancy_company_id ON parsed_vacancy (company_id);

-- Operators of the parser's admin panel. Unrelated to the router's user accounts: there is no
-- registration, the first admin comes from PARSER_ADMIN_USERNAME / PARSER_ADMIN_PASSWORD on
-- startup, and the password is only ever stored as a BCrypt hash.
CREATE TABLE admin (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_admin_username UNIQUE (username)
);
